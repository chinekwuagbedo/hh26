export function OceanAscii() {
  const layerRef = useRef<HTMLElement>(null)

  useGSAP(() => {
    const layer = layerRef.current
    if (!layer || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return

    const moveLayer = gsap.quickTo(layer, "y", { duration: 0.28, ease: "sine.out" })
    const updateParallax = () => {
      const maxScroll = Math.max(1, document.documentElement.scrollHeight - window.innerHeight)
      const progress = Math.min(1, window.scrollY / maxScroll)
      moveLayer(-progress * 180)
    }

    updateParallax()
    window.addEventListener("scroll", updateParallax, { passive: true })
    return () => window.removeEventListener("scroll", updateParallax)
  }, { scope: layerRef })

  return (
    <aside className="ocean-ascii" aria-hidden="true" ref={layerRef}>
      <div className="ocean-ascii-column ocean-ascii-left">
        <pre>{leftCoral}</pre>
        <pre>{leftSprout}</pre>
      </div>
      <div className="ocean-ascii-column ocean-ascii-right">
        <pre>{rightFish}</pre>
        <pre>{rightCoral}</pre>
        <pre>{rightCurrent}</pre>
      </div>
    </aside>
  )
}
